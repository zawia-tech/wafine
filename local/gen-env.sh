#!/usr/bin/env bash
# Generate local-only secrets for the local-first stack.
#
# Why this exists rather than just setting ALLOW_DEV_API_KEY=true: OpenWA refuses to
# boot in production with that flag, and it is RIGHT to — the flag seeds the publicly
# documented `dev-admin-key` as an admin credential. Bypassing the guard locally would
# mean the local stack boots under a security posture the VM never has, which is
# exactly the kind of difference that makes local testing worthless.
#
# So we satisfy the gate instead: a real random API_MASTER_KEY of at least
# MIN_PROD_MASTER_KEY_LENGTH (32) characters. Same posture locally as in production.
#
# Idempotent: refuses to overwrite an existing file unless --force.

set -euo pipefail

ROOT="$(cd "$(dirname "$0")/.." && pwd)"
ENV_FILE="$ROOT/local/.env.local"

if [ -f "$ENV_FILE" ] && [ "${1:-}" != "--force" ]; then
  echo "  $ENV_FILE already exists — leaving it alone (use --force to regenerate)"
  exit 0
fi

# openssl rand -hex 32 = 64 hex chars, comfortably above the 32-char floor and
# never a value on the FORBIDDEN_PROD_SECRETS deny-list.
MASTER="$(openssl rand -hex 32)"
PEPPER="$(openssl rand -hex 32)"

umask 077
cat > "$ENV_FILE" <<EOF
# LOCAL ONLY — gitignored. Generated by local/gen-env.sh on $(date -Is).
# Not for the VM: stack/.env holds the real deployment's secrets.
API_MASTER_KEY=${MASTER}
API_KEY_PEPPER=${PEPPER}
EOF

chmod 600 "$ENV_FILE"
echo "  wrote $ENV_FILE (mode 600)"
echo "  API_MASTER_KEY: ${#MASTER} chars (floor is 32)"
echo
echo "  Run the stack with:"
echo "    --env-file local/.env.local"
